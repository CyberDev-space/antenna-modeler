/**
 * The help that pops up over the names of the parameters: what a parameter
 * is and what it is for, how to set it, what it changes, and its default.
 * Text between backticks is a notation, shown as code.
 */
export interface Topic {
  title: string;
  /** What it is and what it is for, in a sentence or two. */
  what: string;
  /** A small table: the variants, typical values, or how to read a number. */
  table?: { title: string; rows: [name: string, value: string][] };
  /** Short points, one per line. */
  how?: string[];
  /** The heading of the points, if not «Як користуватися». */
  howTitle?: string;
  /** What it changes. */
  affects?: string;
  /** Its default value. */
  defaults?: string;
}

